// Chaves antigas que ainda aparecem em conexões não migradas.
const ALIAS: Record<string, string> = {
  google_calendar: 'google',
  google_sheets: 'google',
}

export const appMarkFor = (appKey: string): Mark | undefined => MARKS[ALIAS[appKey] ?? appKey]

/**
 * `size` é o lado do quadrado. `plain` desenha só o símbolo, sem o quadrado colorido
 * — é o que a barra lateral usa, onde um bloco de cor ao lado de ícones de traço
 * destoaria da fileira inteira.
 */
export function AppLogo({
  appKey,
  icon,
  size = 44,
  plain = false,
  title,
}: {
  appKey: string
  // Glifo do Lucide declarado no manifesto, para App sem marca própria.
  icon?: string | null
  size?: number
  plain?: boolean
  title?: string
}) {
  const mark = appMarkFor(appKey)

  if (!mark) {
    // Sem marca: o glifo do manifesto, e por último um símbolo neutro de conector —
    // nunca um quadrado vazio.
    return <Icon name={icon || 'blocks'} size={plain ? size : Math.round(size * 0.55)} aria-label={title} />
  }

  const glyph = (
    <svg viewBox="0 0 24 24" width={plain ? size : Math.round(size * 0.55)} height={plain ? size : Math.round(size * 0.55)} fill={plain ? mark.color : (mark.fg ?? '#fff')} aria-hidden="true" focusable="false">
      <path d={mark.path} />
    </svg>
  )

  if (plain) return glyph

  return (
    <span
      title={title}
      data-app-logo={appKey}
      style={{
        display: 'inline-flex',
        alignItems: 'center',
        justifyContent: 'center',
        width: size,
        height: size,
        borderRadius: Math.round(size * 0.23),
        background: mark.color,
        flexShrink: 0,
      }}
    >
      {glyph}
    </span>
  )
}
